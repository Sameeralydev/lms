import { Head, Link } from '@inertiajs/react';
import { PageHeader } from '@/components/ui/page-header';
import { WorkspaceLayout } from '@/layouts/workspace-layout';

type Props = {
    tenant: { slug: string };
    receipt: {
        reference: string;
        assignment: string;
        course: string;
        attempt: number;
        submitted_at: string | null;
        status: string;
        late: boolean;
        file_count: number;
    };
};

export default function SubmissionReceipt({ tenant, receipt }: Props) {
    return (
        <WorkspaceLayout title="Submission receipt" area="tenant">
            <Head title="Submission receipt" />
            <PageHeader
                eyebrow="Coursework"
                title="Submission received"
                description="Keep this receipt reference for your records. The timestamp is generated by the server."
            />
            <section
                className="border-border bg-surface mt-6 max-w-2xl rounded-2xl border p-5 sm:p-7"
                aria-labelledby="receipt-heading"
            >
                <h2 id="receipt-heading" className="text-lg font-semibold">
                    {receipt.assignment}
                </h2>
                <dl className="mt-5 grid gap-4 sm:grid-cols-2">
                    {[
                        ['Course', receipt.course],
                        ['Receipt reference', receipt.reference],
                        ['Attempt', String(receipt.attempt)],
                        [
                            'Submitted',
                            receipt.submitted_at
                                ? new Date(receipt.submitted_at).toLocaleString()
                                : 'Recorded',
                        ],
                        ['Status', receipt.late ? 'Submitted late' : 'Submitted'],
                        ['Files', String(receipt.file_count)],
                    ].map(([label, value]) => (
                        <div key={label}>
                            <dt className="text-text-muted text-xs uppercase">{label}</dt>
                            <dd className="mt-1 font-medium break-words">{value}</dd>
                        </div>
                    ))}
                </dl>
                <Link
                    href={`/t/${tenant.slug}/my-assignments`}
                    className="bg-brand-600 focus-ring mt-7 inline-flex min-h-11 items-center rounded-lg px-4 py-2 text-sm font-semibold text-white"
                >
                    Back to my assignments
                </Link>
            </section>
        </WorkspaceLayout>
    );
}
